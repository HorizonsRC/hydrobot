"""Writing and reading saved run configs: the SETUP step's output.

Setup resolves a batch entry into run configs (see ``resolve.py``) and saves
each one as a YAML file in its own run folder (see ``paths.py``). From then on
the file belongs to the analyst: they may edit it by hand and reprocess from
it. So the rules here are deliberately strict:

*   Hydrobot writes a config ONCE and never modifies it afterwards.
*   Setup refuses to overwrite a config that already exists, because that file
    may hold an analyst's edits.
*   Setup is all-or-nothing per batch entry: if anything about an entry can't be
    resolved, or any of its files already exists, nothing for that entry is
    written.

A saved file has two parts. ``setup:`` is a record about the file (versions,
when it was made, which values hydrobot filled in rather than the user). The
Processor ignores the ``setup`` block. Everything else is the run config proper.
"""

import importlib.metadata as md
from datetime import datetime
from pathlib import Path
from typing import Any

import yaml

from hydrobot.orchestration.expansion import RunConfig
from hydrobot.orchestration.paths import run_dir, run_filename
from hydrobot.orchestration.resolve import DATE_FORMAT, ResolveProvider, resolve


# The key holding the record-about-the-file bloc
HEADER_KEY = "setup"


# Written at the very top of every file, for the human who opens it.
_COMMENT = "# Generated by hydrobot setup. Edit the values below, then rerun to reprocess. \n"

# Keys listed first and last, so a file reads: identity, names, ..., dates.
_FIRST_KEYS = (
    "batch",
    "measurement_folder",
    "data_source_code",
    "site",
    "site_code",
    "layer",
    "layer_label",
    "data_family",
    "standard_measurement_name",
    "check_measurement_name",
)
_LAST_KEYS = ("from_date", "to_date")

# Strings we ALWAYS quote, so they can never be read back as a date, number or
# anything else. (Other strings are quoted only if plain style would be misread.)
_ALWAYS_QUOTED_KEYS = {
    "from_date",
    "to_date",
    "set_up_at",
    "hydrobot_version",
    "whurl_version",
    "layer_label",
}
_DATE_KEYS = ("from_date", "to_date")


def package_versions() -> dict[str, str]:
    """Installed versions of the packages that make results reproducible."""
    versions = {}
    for name in ("hydrobot", "whurl"):
        try:
            versions[name] = md.version(name)
        except md.PackageNotFoundError:
            versions[name] = "unknown"
    return versions


def config_path(root: Path | str, run: RunConfig) -> Path:
    """Where a run's saved config lives (pure, touches no files)."""
    return run_dir(root, run) / run_filename(run, "config", "yaml")

def config_document(
    entry: RunConfig,
    run: RunConfig,
    *,
    now: datetime,
    batch_config: str,
    versions: dict[str, str],
) -> dict[str, Any]:
    """Build the content of a saved config: the ``setup`` block, then the run.

    ``filled_by_hydrobot`` lists every key the run has that the batch entry
    did NOT supply itself, whether looked up (``from_date``, ``site_code``) or
    expanded from a template (``standard_measurement_name``, ``layer``). It
    tells an analyst which values they wrote and which hydrobot worked out.
    """
    if HEADER_KEY in run:
        raise ValueError(f"A run config can't have its own {HEADER_KEY!r} key.")

    header = {
        "hydrobot_version": versions["hydrobot"],
        "whurl_version": versions["whurl"],
        "set_up_at": now.strftime(DATE_FORMAT),
        "batch_config": batch_config,
        "filled_by_hydrobot": sorted(k for k in run if entry.get(k) is None),
    }
    return {HEADER_KEY: header, **_in_reading_order(run)}


def write_run_config(root: Path | str, run: RunConfig, document: dict[str, Any]) -> Path:
    """Write one saved config, creating its folder. Never overwrites.

    Raises
    ------
    FileExistsError
        If the file is already there. It may contain an analyst's edits, so
        it is left exactly as it is.
    """
    path = config_path(root, run)
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        # Mode "x" = create, and fail if it exists. Checked by the operating
        # system at the moment of creation, so there's no gap for a race.
        with open(path, "x", encoding="utf-8") as f:
            f.write(_COMMENT)
            f.write(
                yaml.dump(
                    _quote_where_needed(document),
                    Dumper=_Dumper,
                    sort_keys=False,
                    allow_unicode=True,
                    default_flow_style=False,
                )
            )
    except FileExistsError:
        raise FileExistsError(
            f"{path} already exists and was not overwritten: it may contain "
            "an analyst's edits. Delete it yourself if you really want it regenerated."
        ) from None
    return path


def setup_entry(
    root: Path | str,
    entry: RunConfig,
    provider: ResolveProvider,
    *,
    now: datetime,
    batch_config: str,
    versions: dict[str, str],
) -> list[Path]:
    """Resolve one batch entry and save one config per run (all or nothing).

    Everything that can fail is checked BEFORE the first file is written:
    resolving (which may raise, e.g. no from_date for a brand-new site) and
    whether any target file already exists. So a failure never leaves half an
    entry's configs behind.

    Returns
    -------
    list of Path
        The files written, one per run (one per layer for a layered site).
    """
    runs = resolve(entry, provider, now=now)

    existing = [config_path(root, run) for run in runs if config_path(root, run).exists()]
    if existing:
        raise FileExistsError(
            "Not writing anything for this entry: these configs already exist "
            f"(they may hold analyst edits): {[str(p) for p in existing]}"
        )

    return [
        write_run_config(
            root,
            run,
            config_document(entry, run, now=now, batch_config=batch_config, versions=versions),
        )
        for run in runs
    ]


def load_run_config(path: Path | str) -> RunConfig:
    """Read a saved config back as a plain run config (without ``setup``).

    Dates are always returned as text in the standard format. If an analyst
    edited a date and left the quotes off, YAML may have turned it into a
    datetime object; that is converted back so later code only sees text.
    """
    with open(path, encoding="utf-8") as f:
        run = yaml.safe_load(f)
    run.pop(HEADER_KEY, None)
    for key in _DATE_KEYS:
        if isinstance(run.get(key), datetime):
            run[key] = run[key].strftime(DATE_FORMAT)
    return run


# --- Internals ---------------------------------------------------------------


def _in_reading_order(run: RunConfig) -> dict[str, Any]:
    """The run's keys with identity first and dates last; the rest in between."""
    first = {k: run[k] for k in _FIRST_KEYS if k in run}
    last = {k: run[k] for k in _LAST_KEYS if k in run}
    middle = {k: v for k, v in run.items() if k not in first and k not in last}
    return {**first, **middle, **last}


class _Quoted(str):
    """A string that must be written in double quotes."""


class _Dumper(yaml.SafeDumper):
    """A YAML writer that knows how to double-quote ``_Quoted`` strings."""


_Dumper.add_representer(
    _Quoted,
    lambda dumper, text: dumper.represent_scalar(
        "tag:yaml.org,2002:str", str(text), style='"'
    ),
)


def _misread_if_plain(text: str) -> bool:
    """Would writing this string unquoted change its meaning when read back?

    e.g. "true" becomes a boolean, "0.9" a number, "" nothing at all.
    """
    try:
        return yaml.safe_load(text) != text
    except yaml.YAMLError:
        return True


def _quote_where_needed(value: Any, key: str | None = None) -> Any:
    """Copy of ``value`` with strings wrapped in ``_Quoted`` where required."""
    if isinstance(value, dict):
        return {k: _quote_where_needed(v, k) for k, v in value.items()}
    if isinstance(value, list):
        return[_quote_where_needed(v) for v in value]
    if isinstance(value, str) and (key in _ALWAYS_QUOTED_KEYS or _misread_if_plain(value)):
        return _Quoted(value)
    return value
